package com.ntaganira.heritier.ipos.backoffice.service;

import com.ntaganira.heritier.ipos.backoffice.entity.Customer;
import com.ntaganira.heritier.ipos.backoffice.entity.Sale;
import com.ntaganira.heritier.ipos.backoffice.entity.ShopSetting;
import org.springframework.stereotype.Service;
import org.springframework.util.StringUtils;

import java.math.BigDecimal;
import java.time.ZoneId;
import java.time.format.DateTimeFormatter;

@Service
public class EmailTemplateService {

    private static final DateTimeFormatter DATE = DateTimeFormatter.ofPattern("dd MMM yyyy HH:mm");

    public String subject(ShopSetting settings, Sale sale) {
        String template = StringUtils.hasText(settings.getEmailSubjectTemplate())
                ? settings.getEmailSubjectTemplate() : "Receipt {invoiceNumber} from {shopName}";
        return fill(template, settings, sale);
    }

    public String body(ShopSetting settings, Sale sale) {
        String template = StringUtils.hasText(settings.getEmailBodyTemplate())
                ? settings.getEmailBodyTemplate()
                : "Dear {customerName},\n\nThank you for shopping at {shopName}.\n\n"
                + "Receipt: {invoiceNumber}\nDate: {date}\nTotal: {currency} {total}\n\n"
                + "This receipt was generated by iPOS. VAT is included where applicable.\n\n"
                + "{footer}";
        return fill(template, settings, sale);
    }

    private String fill(String template, ShopSetting settings, Sale sale) {
        Customer customer = sale.getCustomer();
        BigDecimal total = sale.getTotal();
        return template
                .replace("{shopName}", safe(settings.getShopName()))
                .replace("{invoiceNumber}", safe(sale.getReceiptNumber()))
                .replace("{customerName}", customer == null ? "Customer" : safe(customer.getName()))
                .replace("{total}", String.format("%,.2f", total))
                .replace("{currency}", safe(settings.getCurrency()))
                .replace("{date}", DATE.format(sale.getSaleDate().atZone(ZoneId.systemDefault())))
                .replace("{footer}", safe(settings.getReceiptFooter()));
    }

    private String safe(String value) {
        return value == null ? "" : value;
    }
}
